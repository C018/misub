/**
 * MiSub ESA 构建脚本：将 functions-esa/index.js 及其依赖打包为单文件
 *
 * 产物：dist-esa/index.js（ESM 单文件，供阿里云 ESA 边缘函数部署）
 * 前置：npm run build（前端 Vite 构建，产物 dist/ 用于 Pages 静态托管）
 *
 * 使用：node scripts/build-esa.mjs
 */
import { build } from 'esbuild';
import { rmSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(rootDir, 'dist-esa');
const outFile = path.join(outDir, 'index.js');

async function main() {
    // 清理旧产物
    if (existsSync(outDir)) {
        rmSync(outDir, { recursive: true, force: true });
    }
    mkdirSync(outDir, { recursive: true });

    const result = await build({
        entryPoints: [path.join(rootDir, 'functions-esa/index.js')],
        outfile: outFile,
        bundle: true,
        format: 'esm',
        platform: 'neutral',
        target: 'es2022',
        sourcemap: false,
        minify: true,
        legalComments: 'none',
        logLevel: 'info',
        metafile: true,
        banner: {
            js: '/* MiSub ESA build - generated by scripts/build-esa.mjs */',
        },
    });

    const outputs = Object.keys(result.metafile.outputs);
    console.log('\n[build-esa] done');
    console.log('  output:', outFile);
    for (const out of outputs) {
        console.log('  size:', (result.metafile.outputs[out].bytes / 1024).toFixed(1) + ' KB');
    }
    console.log('  (limit: 4 MB, recommended keep < 1 MB)');
}

main().catch((err) => {
    console.error('[build-esa] failed:', err);
    process.exit(1);
});
